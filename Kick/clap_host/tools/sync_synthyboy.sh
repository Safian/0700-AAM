#!/usr/bin/env bash
# KICK - repeatable sync of the vendored SynthyBoy tree (Kick/clap_host/builtin/synthyboy) from the SynthyBoyVST repository.
# SPDX-License-Identifier: AGPL-3.0-or-later
#
# Usage: Kick/clap_host/tools/sync_synthyboy.sh [--src DIR] [--ref GITREF] [--dry-run]
#
#   --src DIR    the SynthyBoyVST checkout (default: $SYNTHYBOY_SRC, else ../SynthyBoyVST next to the Kick checkout's parent)
#   --ref REF    commit / branch / tag to sync from (default: develop). The tree is read with `git archive`, so uncommitted files of
#                the checkout never leak in and the same ref always gives the same result.
#   --dry-run    show what rsync would change, write nothing
#
# What is synced (SynthyBoy path -> builtin/synthyboy path; only sources and headers, no tests, no CMake files, no reports):
#   core/include            -> include            core/src               -> src
#   core/<package>          -> <package>          for: engine-own shapes sample-osc granular spectral multisample filters-serum formula
#                                                       tuning wavetable-render wavetable-edit vital-import serum-import fx-serum-a fx-serum-b
#   core/engine-vital       -> engine-vital       the Vital-derived engine + adapter (built only when KICK_SYNTHYBOY_VITAL is ON, never for iOS)
#   shell-clap/*.cpp,*.h    -> .                  the native CLAP shell and the synthyboy.content extension
#   shell-juce/ui           -> shell-juce/ui      the host independent editor library (synthyboy_ui); JUCE is the app's own JUCE
# NOT synced (own build files of KICK): every CMakeLists.txt. The source lists live in Kick/clap_host/CMakeLists.txt; after a sync that
# adds or removes a source file, `git status` shows it and the CMake list must follow (the build fails loudly otherwise).
# The panel registration of the UI library is generated by CMake from the SYNTHYBOY_REGISTER_PANEL lines, nothing to maintain.
#
# Result: builtin/synthyboy/SOURCE records the SynthyBoy commit, the ref, the date of the commit and the sync tool version. The Vital rule
# (docs/ARCHITECTURE.md 2.2 of SynthyBoyVST: no Vital-derived code in iOS builds) is enforced by the CMake option KICK_SYNTHYBOY_VITAL
# and checked by Kick/clap_host/tools/check_no_vital.sh.

set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
dest="$(cd "$here/../builtin/synthyboy" && pwd)"
src="${SYNTHYBOY_SRC:-}"
ref="develop"
dry=0

while [[ $# -gt 0 ]]; do
    case "$1" in
        --src) src="$2"; shift 2 ;;
        --ref) ref="$2"; shift 2 ;;
        --dry-run) dry=1; shift ;;
        -h|--help) sed -n '2,25p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "sync_synthyboy.sh: unknown option: $1 (see --help)" >&2; exit 2 ;;
    esac
done

if [[ -z "$src" ]]; then
    for candidate in "$here/../../../../SynthyBoyVST" "$here/../../../../../SynthyBoyVST" "$HOME/Documents/Projects/Safian/SynthyBoyVST"; do
        if [[ -d "$candidate/.git" || -f "$candidate/.git" ]]; then src="$(cd "$candidate" && pwd)"; break; fi
    done
fi
if [[ -z "$src" || ! -d "$src" ]]; then
    echo "sync_synthyboy.sh: SynthyBoyVST checkout not found; pass --src DIR or set SYNTHYBOY_SRC" >&2
    exit 2
fi

commit="$(git -C "$src" rev-parse --verify "$ref^{commit}")"
commit_date="$(git -C "$src" show -s --format=%cI "$commit")"
subject="$(git -C "$src" show -s --format=%s "$commit")"

tmp="$(mktemp -d "${TMPDIR:-/tmp}/sync-synthyboy.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT
git -C "$src" archive "$commit" core shell-clap shell-juce/ui | tar -x -C "$tmp"

rs=(rsync -a --delete --prune-empty-dirs)
[[ $dry -eq 1 ]] && rs+=(--dry-run --itemize-changes)

# Source filter shared by every package: sources, headers, include fragments, the package README and the license files of imported code.
# tests/ and tools/ are never taken.
filter=(
    --exclude='tests/' --exclude='tools/' --exclude='test_*' --exclude='CMakeLists.txt'
    --include='*/'
    --include='*.cpp' --include='*.c' --include='*.cc' --include='*.h' --include='*.hpp' --include='*.inc' --include='*.inl'
    --include='README.md' --include='LICENSE*' --include='COPYING*' --include='LICENSES/***' --include='Unlicense' --include='BSD-3-Clause'
    --exclude='*'
)

sync_dir() { # <from, relative to the archive> <to, relative to builtin/synthyboy>
    mkdir -p "$dest/$2"
    "${rs[@]}" "${filter[@]}" "$tmp/$1/" "$dest/$2/"
}

sync_dir core/include include
sync_dir core/src src
for pkg in engine-own shapes sample-osc granular spectral multisample filters-serum formula tuning wavetable-render wavetable-edit \
           vital-import serum-import fx-serum-a fx-serum-b engine-vital; do
    sync_dir "core/$pkg" "$pkg"
done
sync_dir shell-juce/ui shell-juce/ui

# the native CLAP shell: top-level files of shell-clap/ only
for f in "$tmp"/shell-clap/*.cpp "$tmp"/shell-clap/*.h; do
    if [[ $dry -eq 1 ]]; then
        cmp -s "$f" "$dest/$(basename "$f")" || echo "would update $(basename "$f")"
    else
        cp "$f" "$dest/$(basename "$f")"
    fi
done

if [[ $dry -eq 0 ]]; then
    {
        echo "SynthyBoyVST commit: $commit"
        echo "ref: $ref"
        echo "commit date: $commit_date"
        echo "subject: $subject"
        echo "synced by: Kick/clap_host/tools/sync_synthyboy.sh"
    } > "$dest/SOURCE"
    echo "sync_synthyboy.sh: synced $commit ($subject) into $dest"
else
    echo "sync_synthyboy.sh: dry run for $commit, nothing written"
fi
